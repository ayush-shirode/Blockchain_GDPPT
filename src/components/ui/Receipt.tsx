import React from "react";
import { Printer, ShieldCheck } from "lucide-react";
import { CopyableCode } from "./CopyableCode";

export interface ReceiptItem {
  label: string;
  value: React.ReactNode;
  isMono?: boolean;
}

interface ReceiptProps {
  title: string;
  receiptNumber: string;
  timestamp: string;
  status: string;
  items: ReceiptItem[];
  footerNote?: string;
}

export function Receipt({
  title,
  receiptNumber,
  timestamp,
  status,
  items,
  footerNote = "Official verification receipt generated by Digital Identity & E-Governance Portal.",
}: ReceiptProps) {
  const handlePrint = () => {
    if (typeof window !== "undefined") {
      window.print();
    }
  };

  return (
    <div className="receipt-container border border-border rounded bg-surface p-6 my-4 shadow-none">
      <div className="flex items-start justify-between border-b border-border pb-4 mb-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <ShieldCheck className="w-5 h-5 text-primary" aria-hidden="true" />
            <h2 className="text-lg font-bold text-text">{title}</h2>
          </div>
          <p className="text-xs text-text-muted">
            Transaction Receipt Reference: <span className="font-mono">{receiptNumber}</span>
          </p>
        </div>
        <button
          type="button"
          onClick={handlePrint}
          className="no-print inline-flex items-center gap-1.5 px-3 py-1.5 rounded border border-border bg-bg text-xs font-medium text-text hover:bg-surface hover:border-primary transition-colors"
        >
          <Printer className="w-3.5 h-3.5" aria-hidden="true" />
          Print Receipt
        </button>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs mb-6">
        <div>
          <span className="text-text-muted block">Timestamp</span>
          <span className="font-mono text-text font-medium">{timestamp}</span>
        </div>
        <div>
          <span className="text-text-muted block">Outcome Status</span>
          <span className="font-semibold text-text uppercase tracking-wide">{status}</span>
        </div>
      </div>

      <dl className="border-t border-b border-border py-4 divide-y divide-border/60 text-xs">
        {items.map((item, idx) => (
          <div key={idx} className="py-2.5 flex flex-col sm:flex-row sm:justify-between sm:items-center gap-1">
            <dt className="text-text-muted font-medium">{item.label}</dt>
            <dd className={`text-text ${item.isMono ? "font-mono" : ""}`}>
              {typeof item.value === "string" ? (
                item.isMono && item.value.length > 20 ? (
                  <CopyableCode value={item.value} truncateLength={28} />
                ) : (
                  item.value
                )
              ) : (
                item.value
              )}
            </dd>
          </div>
        ))}
      </dl>

      <div className="mt-4 pt-2 text-[11px] text-text-muted flex justify-between items-center">
        <span>{footerNote}</span>
        <span className="font-mono">SEC-RECEIPT-v2</span>
      </div>
    </div>
  );
}
